-- Additive tables only. Failed transaction rolls back the new tables.
-- Keep successfully deployed history on application rollback; do not drop it.
CREATE TABLE intervention_policy_states (
    session_id BIGINT PRIMARY KEY REFERENCES learning_sessions(id),
    timeline_json JSONB NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0)
);
CREATE TABLE intervention_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id),
    type VARCHAR(32) NOT NULL CHECK (type IN ('OFF_TASK','BREAK_SUGGESTION')),
    status VARCHAR(32) NOT NULL CHECK
        (status IN ('PENDING','ACKNOWLEDGED','DISMISSED','EXPIRED')),
    cause BIGINT NOT NULL CHECK (cause >= 0),
    pending_slot INTEGER,
    channels_json JSONB NOT NULL,
    policy_version VARCHAR(64) NOT NULL,
    running_since TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at >= created_at),
    acted_at TIMESTAMPTZ,
    delivery_confirmed_at TIMESTAMPTZ,
    CONSTRAINT uq_intervention_cause UNIQUE (session_id,type,cause),
    CONSTRAINT uq_intervention_pending UNIQUE (session_id,type,pending_slot),
    CONSTRAINT ck_intervention_slot CHECK
        ((status = 'PENDING' AND pending_slot IS NOT NULL AND pending_slot = 1)
         OR (status <> 'PENDING' AND pending_slot IS NULL)),
    CONSTRAINT ck_intervention_ack CHECK
        ((status IN ('ACKNOWLEDGED','DISMISSED') AND acted_at IS NOT NULL)
         OR (status IN ('PENDING','EXPIRED') AND acted_at IS NULL))
);
CREATE INDEX ix_intervention_history ON intervention_events(session_id,created_at,id);
