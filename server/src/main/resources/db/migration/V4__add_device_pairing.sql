-- Issue #58. Additive migration; V1/V2 remain unchanged.
-- PostgreSQL rolls back this entire migration on failure. Inspect existing active installation
-- duplicates before retrying; never delete devices or populated tables to force application.
ALTER TABLE user_devices ADD CONSTRAINT fk_user_devices_parent_owner
    FOREIGN KEY (linked_desktop_device_id, user_id) REFERENCES user_devices (id, user_id);
CREATE UNIQUE INDEX uq_user_devices_active_extension_installation
    ON user_devices (installation_id_hash)
    WHERE device_type = 'CHROME_EXTENSION' AND status = 'ACTIVE';

CREATE TABLE pairing_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    issuer_desktop_device_id BIGINT NOT NULL,
    code_hash CHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_by_extension_device_id BIGINT,
    consumed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    terminal_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_pairing_codes_hash UNIQUE (code_hash),
    CONSTRAINT fk_pairing_codes_issuer_owner FOREIGN KEY (issuer_desktop_device_id, user_id)
        REFERENCES user_devices (id, user_id),
    CONSTRAINT fk_pairing_codes_consumer_owner
        FOREIGN KEY (consumed_by_extension_device_id, user_id)
        REFERENCES user_devices (id, user_id),
    CONSTRAINT ck_pairing_codes_hash CHECK (code_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_pairing_codes_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_pairing_codes_state CHECK (
        (status = 'ACTIVE' AND terminal_at IS NULL AND consumed_at IS NULL
            AND cancelled_at IS NULL AND consumed_by_extension_device_id IS NULL)
        OR (status = 'CONSUMED' AND terminal_at IS NOT NULL AND terminal_at = consumed_at AND consumed_at IS NOT NULL
            AND consumed_by_extension_device_id IS NOT NULL AND cancelled_at IS NULL)
        OR (status = 'EXPIRED' AND terminal_at IS NOT NULL AND terminal_at = expires_at AND consumed_at IS NULL
            AND cancelled_at IS NULL AND consumed_by_extension_device_id IS NULL)
        OR (status = 'CANCELLED' AND terminal_at IS NOT NULL AND terminal_at = cancelled_at AND cancelled_at IS NOT NULL
            AND consumed_at IS NULL AND consumed_by_extension_device_id IS NULL))
);
CREATE UNIQUE INDEX uq_pairing_codes_active_desktop ON pairing_codes (issuer_desktop_device_id)
    WHERE status = 'ACTIVE';
CREATE INDEX ix_pairing_codes_expiry ON pairing_codes (expires_at) WHERE status = 'ACTIVE';
CREATE INDEX ix_pairing_codes_terminal ON pairing_codes (terminal_at) WHERE terminal_at IS NOT NULL;

CREATE TABLE pairing_installation_attempts (
    installation_id_hash CHAR(64) PRIMARY KEY,
    failed_attempts SMALLINT NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_pairing_attempts_hash CHECK (installation_id_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_pairing_attempts_state CHECK (
        (failed_attempts BETWEEN 0 AND 2 AND locked_until IS NULL)
        OR (failed_attempts = 3 AND locked_until IS NOT NULL))
);
CREATE INDEX ix_pairing_attempts_locked_until ON pairing_installation_attempts (locked_until)
    WHERE locked_until IS NOT NULL;

-- 미완료 실패의 24시간 보관 만료 조회를 지원한다.
CREATE INDEX ix_pairing_attempts_pending_updated ON pairing_installation_attempts (updated_at)
    WHERE failed_attempts IN (1, 2) AND locked_until IS NULL;
