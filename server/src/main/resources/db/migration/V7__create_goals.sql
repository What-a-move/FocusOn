CREATE TABLE goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    goal_text VARCHAR(40) NOT NULL,
    normalized_goal_text VARCHAR(200),
    confirmation_source VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_goals_text_length CHECK (char_length(goal_text) BETWEEN 2 AND 40),
    CONSTRAINT ck_goals_source CHECK (confirmation_source IN ('AI_CONFIRMED', 'MANUAL_CONFIRMED')),
    CONSTRAINT ck_goals_status CHECK (status IN ('ACTIVE', 'ARCHIVED', 'DELETED'))
);

CREATE INDEX ix_goals_user_id ON goals (user_id);
