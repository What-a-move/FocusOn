-- #288 학습 정리 생성 작업 상태와 최소 복습 근거를 저장한다.
-- 근거에는 원문·URL·코드·개인정보를 넣지 않으며 개념 라벨만 120자 이하로 둔다.
ALTER TABLE learning_summaries
    ADD COLUMN input_cutoff_at TIMESTAMPTZ,
    ADD COLUMN attempt_count SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN next_attempt_at TIMESTAMPTZ,
    ADD COLUMN lease_until TIMESTAMPTZ,
    ADD COLUMN evidence_count INTEGER,
    ADD COLUMN model_version VARCHAR(64),
    ADD COLUMN error_code VARCHAR(32),
    ADD COLUMN generated_at TIMESTAMPTZ,
    ADD COLUMN updated_at TIMESTAMPTZ;

ALTER TABLE learning_summaries
    ADD CONSTRAINT ck_learning_summary_attempts CHECK (attempt_count BETWEEN 0 AND 3);

CREATE INDEX ix_learning_summaries_due
    ON learning_summaries (summary_status, next_attempt_at);

CREATE TABLE learning_review_evidences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id),
    concept_label VARCHAR(120) NOT NULL,
    evidence_type VARCHAR(32) NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    content_source VARCHAR(32) NOT NULL,
    dedupe_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_review_evidence_label CHECK (length(trim(concept_label)) > 0),
    CONSTRAINT uq_review_evidence_session_hash UNIQUE (session_id, dedupe_hash)
);
