-- Additive migration. A failed transaction rolls back this new table; do not drop
-- a successfully deployed table to roll back application code (history would be lost).
CREATE TABLE analysis_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id),
    device_id BIGINT NOT NULL REFERENCES user_devices(id),
    client_run_id UUID NOT NULL,
    content_source VARCHAR(32) NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    sequence BIGINT NOT NULL CHECK (sequence > 0),
    relation VARCHAR(32) NOT NULL,
    relation_confidence DECIMAL(4,3) CHECK (relation_confidence BETWEEN 0 AND 1),
    analysis_status VARCHAR(32) NOT NULL,
    reason_code VARCHAR(80),
    error_code VARCHAR(80),
    model_version VARCHAR(64),
    prompt_version VARCHAR(64),
    policy_version VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_analysis_client_run UNIQUE (session_id, client_run_id),
    CONSTRAINT ck_analysis_source CHECK (content_source IN
        ('APP_META', 'TAB_META', 'CHROME_DOM', 'DESKTOP_APP_OCR')),
    CONSTRAINT ck_analysis_relation CHECK (relation IN
        ('RELATED', 'UNRELATED', 'UNCERTAIN', 'EXCLUDED', 'PRIVACY_BLOCKED')),
    CONSTRAINT ck_analysis_status CHECK (analysis_status IN
        ('COMPLETED', 'NEEDS_CONFIRMATION', 'SKIPPED', 'ERROR')),
    CONSTRAINT ck_analysis_reason CHECK (reason_code IN
        ('SEMANTIC_GOAL_MATCH', 'SEMANTIC_GOAL_MISMATCH', 'INSUFFICIENT_CONTEXT',
         'AMBIGUOUS_CONTEXT', 'ANALYSIS_UNAVAILABLE')),
    CONSTRAINT ck_analysis_guard CHECK (relation NOT IN ('EXCLUDED', 'PRIVACY_BLOCKED')
        OR (analysis_status = 'SKIPPED' AND relation_confidence IS NULL
            AND reason_code IS NULL AND model_version IS NULL AND prompt_version IS NULL))
);
CREATE INDEX ix_analysis_current_device
    ON analysis_runs (session_id, device_id, observed_at DESC, id DESC);
CREATE INDEX ix_analysis_session_history ON analysis_runs (session_id, observed_at, id);
