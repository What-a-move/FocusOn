CREATE TABLE user_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    consent_type VARCHAR(32) NOT NULL,
    is_granted BOOLEAN NOT NULL,
    consent_version VARCHAR(32) NOT NULL,
    granted_at TIMESTAMPTZ,
    withdrawn_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_consents_user_type UNIQUE (user_id, consent_type),
    CONSTRAINT ck_user_consents_type CHECK (consent_type IN
        ('TERMS_OF_SERVICE', 'PRIVACY_POLICY', 'SCREEN_ANALYSIS', 'CAMERA_ANALYSIS'))
);

CREATE TABLE user_focus_settings (
    user_id BIGINT PRIMARY KEY REFERENCES users (id),
    intervention_level VARCHAR(16) NOT NULL,
    notification_channels VARCHAR(255) NOT NULL,
    break_suggestion_enabled BOOLEAN NOT NULL,
    camera_analysis_enabled BOOLEAN NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_focus_settings_level CHECK (intervention_level IN ('GENTLE', 'NORMAL', 'ACTIVE'))
);

CREATE TABLE user_analysis_excluded_domains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    host VARCHAR(253) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_analysis_excluded_domains_user_host UNIQUE (user_id, host)
);

CREATE INDEX ix_user_analysis_excluded_domains_user_id
    ON user_analysis_excluded_domains (user_id);
