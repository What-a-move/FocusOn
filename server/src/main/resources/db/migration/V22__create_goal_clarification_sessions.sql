-- 유효기간과 보관 기간은 다르며, 만료된 이력은 자동 삭제하지 않는다.
CREATE TABLE goal_clarification_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    goal_text VARCHAR(40) NOT NULL,
    conversation_turn INTEGER NOT NULL DEFAULT 0,
    state_json JSONB NOT NULL,
    status VARCHAR(16) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_goal_clarification_turn CHECK (conversation_turn BETWEEN 0 AND 2),
    CONSTRAINT ck_goal_clarification_status CHECK (status IN ('PROCESSING', 'READY', 'CONFIRMED')),
    CONSTRAINT uq_goal_clarification_id_user UNIQUE (id, user_id)
);
CREATE INDEX ix_goal_clarification_owner_expiry
    ON goal_clarification_sessions (user_id, expires_at);

ALTER TABLE goals ADD COLUMN clarification_session_id BIGINT;
ALTER TABLE goals ADD CONSTRAINT fk_goals_clarification_owner
    FOREIGN KEY (clarification_session_id, user_id)
    REFERENCES goal_clarification_sessions (id, user_id);
