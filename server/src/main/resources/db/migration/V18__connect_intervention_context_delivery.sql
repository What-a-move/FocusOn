CREATE TABLE session_observation_contexts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id),
    runner_device_id BIGINT NOT NULL REFERENCES user_devices(id),
    observer_device_id BIGINT REFERENCES user_devices(id),
    observer VARCHAR(16) NOT NULL CHECK (observer IN ('DESKTOP','EXTENSION','NONE')),
    client_context_id UUID NOT NULL,
    foreground_sequence BIGINT NOT NULL CHECK
        (foreground_sequence BETWEEN 1 AND 9007199254740991),
    running_since TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    valid_until TIMESTAMPTZ NOT NULL CHECK (valid_until >= created_at),
    CONSTRAINT uq_context_nonce UNIQUE (session_id,client_context_id),
    CONSTRAINT uq_context_sequence UNIQUE (session_id,foreground_sequence),
    CONSTRAINT ck_context_observer CHECK
        ((observer = 'NONE' AND observer_device_id IS NULL)
         OR (observer <> 'NONE' AND observer_device_id IS NOT NULL))
);
ALTER TABLE analysis_runs ADD COLUMN observation_context_id BIGINT
    REFERENCES session_observation_contexts(id);
ALTER TABLE intervention_events ADD COLUMN observation_context_id BIGINT
    REFERENCES session_observation_contexts(id);
CREATE TABLE intervention_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intervention_id BIGINT NOT NULL REFERENCES intervention_events(id),
    client_delivery_id UUID NOT NULL,
    dispatch_status VARCHAR(16) NOT NULL CHECK
        (dispatch_status IN ('SENT','NOT_SENT','UNKNOWN')),
    channels_json JSONB NOT NULL,
    accepted_at TIMESTAMPTZ NOT NULL,
    cooldown_until TIMESTAMPTZ,
    CONSTRAINT uq_delivery_nonce UNIQUE (intervention_id,client_delivery_id)
);
CREATE INDEX ix_delivery_event ON intervention_deliveries(intervention_id,id);

-- 전송 확인 뒤에도 사용자 반응 PENDING은 유지하되 미전송 후보 slot은 해제한다.
ALTER TABLE intervention_events DROP CONSTRAINT ck_intervention_slot;
ALTER TABLE intervention_events ADD CONSTRAINT ck_intervention_slot CHECK
    ((status = 'PENDING' AND
        ((delivery_confirmed_at IS NULL AND pending_slot IS NOT NULL AND pending_slot = 1)
         OR (delivery_confirmed_at IS NOT NULL AND pending_slot IS NULL)))
     OR (status <> 'PENDING' AND pending_slot IS NULL));
