-- Issue #288 학습 정리 생성 파이프라인. 테이블·컬럼 추가만 하며 기존 세션 기록은 바꾸지 않는다.
-- 실패한 트랜잭션은 전체가 rollback된다. 적용된 뒤 코드를 되돌릴 때 이 테이블을 지우지 않는다(근거 이력 유실).

-- 작업 점유·재시도에 필요한 값이다. input_closes_at 이전에 받은 근거만 정리 입력으로 쓴다.
ALTER TABLE learning_summaries
    ADD COLUMN input_closes_at TIMESTAMPTZ,
    ADD COLUMN next_attempt_at TIMESTAMPTZ,
    ADD COLUMN lease_expires_at TIMESTAMPTZ,
    ADD COLUMN attempt_count SMALLINT NOT NULL DEFAULT 0;

-- V19 이후 생성기 없이 들어간 대기 행은 지금부터 처리하도록 기준 시각을 채운다.
-- GENERATING은 점유한 Worker가 없으므로 QUEUED로 되돌린다. 종료 행은 그대로 둔다.
UPDATE learning_summaries ls SET
    summary_status = 'QUEUED',
    input_closes_at = coalesce(s.ended_at + INTERVAL '30 seconds', CURRENT_TIMESTAMP),
    next_attempt_at = coalesce(s.ended_at + INTERVAL '30 seconds', CURRENT_TIMESTAMP)
FROM learning_sessions s
WHERE s.id = ls.session_id AND ls.summary_status IN ('QUEUED', 'GENERATING');

ALTER TABLE learning_summaries
    ADD CONSTRAINT ck_learning_summary_attempts CHECK (attempt_count BETWEEN 0 AND 3),
    ADD CONSTRAINT ck_learning_summary_queue CHECK (
        (summary_status = 'QUEUED' AND input_closes_at IS NOT NULL
            AND next_attempt_at IS NOT NULL AND lease_expires_at IS NULL)
        OR (summary_status = 'GENERATING' AND input_closes_at IS NOT NULL
            AND lease_expires_at IS NOT NULL AND attempt_count > 0)
        OR (summary_status IN ('READY', 'INSUFFICIENT_DATA', 'FAILED')
            AND next_attempt_at IS NULL AND lease_expires_at IS NULL));

-- Worker 후보 조회용. 종료 상태 행은 색인에 넣지 않는다.
CREATE INDEX ix_learning_summary_due ON learning_summaries (next_attempt_at)
    WHERE summary_status = 'QUEUED';
CREATE INDEX ix_learning_summary_lease ON learning_summaries (lease_expires_at)
    WHERE summary_status = 'GENERATING';
-- 정리 행이 빠진 최근 종료 세션을 찾는 복구 조회용이다.
CREATE INDEX ix_learning_sessions_ended_at ON learning_sessions (ended_at)
    WHERE status = 'ENDED';

-- RELATED 화면에서 만든 최소 근거다. 원문·URL·제목은 저장하지 않고 120자 이하 개념만 둔다.
-- 같은 세션 안의 같은 근거는 evidence_hash로 한 번만 저장하므로 행 수가 곧 서로 다른 근거 수다.
CREATE TABLE learning_review_evidences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id),
    analysis_run_id BIGINT NOT NULL REFERENCES analysis_runs(id),
    concept VARCHAR(120) NOT NULL,
    evidence_hash VARCHAR(64) NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    relation_confidence DECIMAL(4,3),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_learning_review_evidence UNIQUE (session_id, evidence_hash),
    CONSTRAINT ck_learning_review_evidence_hash CHECK (evidence_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_learning_review_evidence_concept CHECK (learning_summary_nonblank(concept)),
    CONSTRAINT ck_learning_review_evidence_confidence CHECK (
        relation_confidence IS NULL OR relation_confidence BETWEEN 0 AND 1)
);
CREATE INDEX ix_learning_review_evidence_session
    ON learning_review_evidences (session_id, created_at);
