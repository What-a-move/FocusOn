-- Issue #32: authentication storage only. Later domains use separate migrations.
-- This migration creates new tables and is not automatically reversible after data is written.
-- On failure before Flyway records V1, PostgreSQL rolls back the migration transaction;
-- inspect flyway_schema_history and retry after correcting the cause. Do not drop populated tables.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(12),
    onboarding_status VARCHAR(16) NOT NULL DEFAULT 'INCOMPLETE',
    user_time_zone VARCHAR(64) NOT NULL DEFAULT 'Asia/Seoul',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT ck_users_onboarding_status
        CHECK (onboarding_status IN ('INCOMPLETE', 'COMPLETED'))
);

CREATE UNIQUE INDEX uq_users_nickname
    ON users (nickname) WHERE nickname IS NOT NULL;

CREATE TABLE oauth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    provider VARCHAR(32) NOT NULL,
    provider_subject VARCHAR(255) NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unlinked_at TIMESTAMPTZ,
    CONSTRAINT uq_oauth_identities_provider_subject UNIQUE (provider, provider_subject),
    CONSTRAINT ck_oauth_identities_provider CHECK (provider IN ('GOOGLE'))
);

CREATE INDEX ix_oauth_identities_user_id ON oauth_identities (user_id);

CREATE TABLE user_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    device_type VARCHAR(32) NOT NULL,
    installation_id_hash CHAR(64) NOT NULL,
    display_name VARCHAR(80) NOT NULL,
    linked_desktop_device_id BIGINT REFERENCES user_devices (id),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_devices_installation
        UNIQUE (user_id, device_type, installation_id_hash),
    CONSTRAINT ck_user_devices_device_type
        CHECK (device_type IN ('DESKTOP', 'CHROME_EXTENSION')),
    CONSTRAINT ck_user_devices_status
        CHECK (status IN ('ACTIVE', 'REVOKED', 'LOGGED_OUT')),
    CONSTRAINT ck_user_devices_desktop_link
        CHECK (device_type <> 'DESKTOP' OR linked_desktop_device_id IS NULL),
    CONSTRAINT ck_user_devices_installation_hash
        CHECK (installation_id_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX ix_user_devices_user_status_type
    ON user_devices (user_id, status, device_type);
CREATE INDEX ix_user_devices_linked_desktop
    ON user_devices (linked_desktop_device_id)
    WHERE linked_desktop_device_id IS NOT NULL;

CREATE TABLE token_families (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    device_id BIGINT NOT NULL REFERENCES user_devices (id),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    revoked_reason VARCHAR(32),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_token_families_status
        CHECK (status IN ('ACTIVE', 'REVOKED', 'EXPIRED')),
    CONSTRAINT ck_token_families_revoked_reason
        CHECK (revoked_reason IS NULL OR revoked_reason IN
            ('LOGOUT', 'UNLINK', 'TOKEN_REUSE', 'DEVICE_REVOKED')),
    CONSTRAINT ck_token_families_expiry
        CHECK (expires_at > created_at)
);

CREATE INDEX ix_token_families_device_status
    ON token_families (device_id, status);
CREATE INDEX ix_token_families_user_id ON token_families (user_id);
CREATE UNIQUE INDEX uq_token_families_active_device
    ON token_families (device_id) WHERE status = 'ACTIVE';

CREATE TABLE refresh_token_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_family_id BIGINT NOT NULL REFERENCES token_families (id),
    token_hash CHAR(64) NOT NULL,
    parent_token_id BIGINT REFERENCES refresh_token_records (id),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT uq_refresh_token_records_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_token_records_status
        CHECK (status IN ('ACTIVE', 'ROTATED', 'REVOKED', 'EXPIRED')),
    CONSTRAINT ck_refresh_token_records_token_hash
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_token_records_expiry
        CHECK (expires_at > issued_at)
);

CREATE INDEX ix_refresh_token_records_family_id
    ON refresh_token_records (token_family_id);
CREATE INDEX ix_refresh_token_records_parent_id
    ON refresh_token_records (parent_token_id)
    WHERE parent_token_id IS NOT NULL;
CREATE UNIQUE INDEX uq_refresh_token_records_active_family
    ON refresh_token_records (token_family_id) WHERE status = 'ACTIVE';
