-- 적용 후 롤백은 세션 데이터 삭제를 수반하므로 별도 승인과 백업이 필요하다.
CREATE TABLE learning_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    goal_id BIGINT NOT NULL REFERENCES goals (id),
    runner_device_id BIGINT NOT NULL REFERENCES user_devices (id),
    goal_text_snapshot VARCHAR(40) NOT NULL,
    status VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL,
    target_duration_ms BIGINT NOT NULL,
    accumulated_active_ms BIGINT NOT NULL,
    last_resumed_at TIMESTAMPTZ,
    last_heartbeat_at TIMESTAMPTZ,
    pause_reason VARCHAR(32),
    end_reason VARCHAR(32),
    user_time_zone_snapshot VARCHAR(64) NOT NULL,
    study_date DATE NOT NULL,
    session_options_snapshot_json JSONB NOT NULL,
    intervention_policy_version VARCHAR(64) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_learning_session_status CHECK (status IN ('RUNNING', 'PAUSED', 'AUTO_PAUSED',
        'AWAITING_END_CONFIRMATION', 'ENDING', 'ENDED', 'ABANDONED')),
    CONSTRAINT ck_learning_session_duration CHECK (target_duration_ms > 0
        AND accumulated_active_ms >= 0),
    CONSTRAINT ck_learning_session_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_learning_sessions_active_user ON learning_sessions (user_id)
    WHERE status IN ('RUNNING', 'PAUSED', 'AUTO_PAUSED', 'AWAITING_END_CONFIRMATION', 'ENDING');
CREATE INDEX ix_learning_sessions_user_started ON learning_sessions (user_id, started_at DESC);

CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    scope VARCHAR(32) NOT NULL,
    idempotency_key UUID NOT NULL,
    request_hash CHAR(64) NOT NULL,
    response_status SMALLINT NOT NULL,
    response_body_json JSONB NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_idempotency_user_scope_key UNIQUE (user_id, scope, idempotency_key),
    CONSTRAINT ck_idempotency_scope CHECK (scope IN ('CREATE_SESSION', 'PAUSE_SESSION',
        'RESUME_SESSION', 'EXTEND_SESSION', 'END_SESSION'))
);
