-- #317 재설계 1차: 일시정지·재개 구간을 남겨 집중 리포트 가로축(일시정지를 뺀 경과 시간)을 계산한다.
-- pause·자동 일시정지 때 열고 resume 때 닫는다. 재개 없이 끝나면 resumed_at은 NULL로 남는다.
-- 도입 전 세션은 행이 없다. 화면·사용자 원문은 저장하지 않는다.
-- 복구: 새 테이블만 추가하므로 `DROP TABLE session_pauses;` 뒤 flyway_schema_history에서 version 33
-- 행을 지우면 된다(일시정지 구간 기록만 사라진다).
CREATE TABLE session_pauses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id) ON DELETE CASCADE,
    paused_at TIMESTAMPTZ NOT NULL,
    resumed_at TIMESTAMPTZ,
    pause_reason VARCHAR(32) NOT NULL,
    CONSTRAINT ck_session_pauses_order CHECK (resumed_at IS NULL OR resumed_at >= paused_at)
);
CREATE INDEX idx_session_pauses_session ON session_pauses(session_id, paused_at, id);
-- 세션마다 열린 구간은 하나뿐이다.
CREATE UNIQUE INDEX uq_session_pauses_open ON session_pauses(session_id) WHERE resumed_at IS NULL;
