-- 연장은 재시도가 아닌 실제 성공마다 이력을 남긴다. 기존 세션 데이터는 변경하지 않는다.
CREATE TABLE session_extensions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id),
    additional_duration_ms BIGINT NOT NULL,
    previous_target_duration_ms BIGINT NOT NULL,
    target_duration_ms BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_session_extension_duration CHECK (additional_duration_ms > 0),
    CONSTRAINT ck_session_extension_targets CHECK (target_duration_ms > previous_target_duration_ms)
);
CREATE INDEX ix_session_extensions_session_id ON session_extensions(session_id, created_at);
