-- 기존 세션과 시간은 변경하지 않고 새 수신 이력/학습 정리만 추가한다.
CREATE TABLE session_local_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES learning_sessions(id),
    device_id BIGINT NOT NULL REFERENCES user_devices(id),
    event_code VARCHAR(64) NOT NULL CHECK (event_code IN (
        'LOCAL_SCREEN_PERMISSION_REVOKED', 'LOCAL_EXTENSION_HOST_PERMISSION_MISSING')),
    event_hash VARCHAR(64) NOT NULL CHECK (event_hash ~ '^[0-9a-f]{64}$'),
    occurred_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_session_local_event UNIQUE (session_id, device_id, event_hash)
);
-- 승인된 개념 스키마와 텍스트 길이만 검사한다. 원문 수집/AI 생성은 이 migration에 없다.
CREATE FUNCTION learning_summary_concept_length(concepts JSONB) RETURNS BIGINT
LANGUAGE SQL IMMUTABLE STRICT AS $$
    SELECT CASE WHEN coalesce(bool_and(coalesce(
        jsonb_typeof(item) = 'object'
        AND jsonb_typeof(item->'name') = 'string'
        AND length(trim(item->>'name')) > 0
        AND jsonb_typeof(item->'briefExplanation') = 'string'
        AND length(trim(item->>'briefExplanation')) > 0
        AND (NOT item ? 'sessionEvidence' OR item->'sessionEvidence' = 'null'::jsonb
            OR jsonb_typeof(item->'sessionEvidence') = 'string')
        AND CASE WHEN jsonb_typeof(item) = 'object' THEN
            item - ARRAY['name','briefExplanation','sessionEvidence'] = '{}'::jsonb
            ELSE false END, false)
    ), true) THEN coalesce(sum(length(item->>'name') + length(item->>'briefExplanation')
        + coalesce(length(item->>'sessionEvidence'), 0)), 0) ELSE -1 END
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(concepts) = 'array'
        THEN concepts ELSE '[]'::jsonb END) AS item
$$;
CREATE TABLE learning_summaries (
    session_id BIGINT PRIMARY KEY REFERENCES learning_sessions(id),
    summary_status VARCHAR(32) NOT NULL CHECK (summary_status IN (
        'QUEUED', 'GENERATING', 'READY', 'INSUFFICIENT_DATA', 'FAILED')),
    overview VARCHAR(1200),
    key_concepts JSONB NOT NULL DEFAULT '[]'::jsonb,
    next_start_prompt VARCHAR(1200),
    CONSTRAINT ck_learning_summary_concepts CHECK (
        jsonb_typeof(key_concepts) = 'array' AND jsonb_array_length(key_concepts) <= 5),
    CONSTRAINT ck_learning_summary_ready CHECK (
        (summary_status = 'READY' AND overview IS NOT NULL AND length(trim(overview)) > 0
        AND next_start_prompt IS NOT NULL AND length(trim(next_start_prompt)) > 0)
        OR (summary_status <> 'READY' AND overview IS NULL AND next_start_prompt IS NULL
        AND key_concepts = '[]'::jsonb)),
    CONSTRAINT ck_learning_summary_length CHECK (
        learning_summary_concept_length(key_concepts) >= 0
        AND coalesce(length(overview), 0) + coalesce(length(next_start_prompt), 0)
        + learning_summary_concept_length(key_concepts) <= 1200)
);
