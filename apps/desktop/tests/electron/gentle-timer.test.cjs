const assert = require('node:assert/strict')
const test = require('node:test')
const { createGentleTimer } = require('../../features/floating/gentle-timer.ts')

test('약한 팻말은 올라온 뒤 4초에 내려간다', ({ mock }) => {
  mock.timers.enable({ apis: ['setTimeout'] })
  const hide = mock.fn()
  const timer = createGentleTimer(hide)
  timer.start(700)
  mock.timers.tick(4699)
  assert.equal(hide.mock.callCount(), 0)
  mock.timers.tick(1)
  assert.equal(hide.mock.callCount(), 1)
})

test('마우스가 팻말에 머무르면 기다리고 떠난 뒤 1.5초에 내려간다', ({ mock }) => {
  mock.timers.enable({ apis: ['setTimeout'] })
  const hide = mock.fn()
  const timer = createGentleTimer(hide)
  timer.start(0)
  mock.timers.tick(3999)
  timer.enter()
  mock.timers.tick(5000)
  assert.equal(hide.mock.callCount(), 0)
  timer.leave()
  mock.timers.tick(1499)
  assert.equal(hide.mock.callCount(), 0)
  mock.timers.tick(1)
  assert.equal(hide.mock.callCount(), 1)
  timer.leave()
  timer.cancel()
  mock.timers.tick(1500)
  assert.equal(hide.mock.callCount(), 1)
})
